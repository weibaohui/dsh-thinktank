const MODEL_BY_ID = {}
for (const m of MODELS) MODEL_BY_ID[m.id] = m

const CATEGORY_BY_ID = {}
for (const c of CATEGORIES) CATEGORY_BY_ID[c.id] = c

/** 目录摘要（client 选择器用）：不含 points/qs，减小传输。 */
function catalog() {
  return {
    categories: CATEGORIES.map((c) => ({ ...c })),
    models: MODELS.map((m) => ({
      id: m.id, name: m.name, en: m.en, cat: m.cat, def: m.def, scenes: m.scenes,
    })),
  }
}

function getModel(id) { return MODEL_BY_ID[id] || null }

function getModels(ids) {
  if (!Array.isArray(ids)) return []
  const seen = new Set()
  const out = []
  for (const id of ids) {
    if (typeof id !== 'string' || seen.has(id)) continue
    const m = MODEL_BY_ID[id]
    if (m) { seen.add(id); out.push(m) }
  }
  return out
}

/**
 * 本地启发式推荐：把问题文本切成 n-gram，与模型名称/定义/场景关键词比对打分。
 * 无需 AI，毫秒返回。返回 [{id, score, hits}] 按分数降序。
 */
function recommend(question, limit = 12) {
  const q = String(question || '').toLowerCase()
  if (!q.trim()) return []
  const grams = new Set()
  for (const n of [2, 3, 4]) {
    for (let i = 0; i + n <= q.length; i++) grams.add(q.slice(i, i + n))
  }
  const scored = []
  for (const m of MODELS) {
    let score = 0
    const hits = []
    const fields = [
      { text: m.name.toLowerCase(), w: 6 },
      { text: (m.en || '').toLowerCase(), w: 3 },
      { text: m.def.toLowerCase(), w: 2 },
      { text: m.scenes.join(' ').toLowerCase(), w: 8 },
      { text: m.points.join(' ').toLowerCase(), w: 1 },
    ]
    for (const f of fields) {
      if (!f.text) continue
      for (const g of grams) {
        if (g.length < 2 || !/[一-鿿a-z]/.test(g)) continue
        if (f.text.includes(g)) { score += f.w * g.length; if (f.w >= 6) hits.push(g) }
      }
    }
    if (score > 0) scored.push({ id: m.id, score, hits: [...new Set(hits)].slice(0, 3) })
  }
  scored.sort((a, b) => b.score - a.score)
  return scored.slice(0, limit)
}

/** 导出 Markdown 版完整报告（client 导出与 host 兜底共用）。 */
function reportMarkdown(report) {
  const lines = []
  lines.push(`# 智囊团 · 思维模型综合分析报告`)
  lines.push('')
  lines.push(`> **问题**：${report.question || ''}`)
  if (report.context) lines.push(`> **背景**：${report.context}`)
  lines.push(`> **时间**：${report.createdAt || ''} · **模型数**：${(report.results || []).length}`)
  lines.push('')
  const syn = report.synthesis
  if (syn && syn.summary) {
    lines.push('## 综合结论')
    lines.push('')
    lines.push(syn.summary)
    lines.push('')
    const list = (title, arr) => {
      if (!Array.isArray(arr) || !arr.length) return
      lines.push(`### ${title}`)
      for (const it of arr) lines.push(`- ${typeof it === 'string' ? it : it.action || it.text || JSON.stringify(it)}`)
      lines.push('')
    }
    list('🤝 模型共识', syn.consensus)
    list('⚡ 观点分歧', syn.conflicts)
    list('🕳️ 盲区提醒', syn.blindspots)
    if (Array.isArray(syn.priorities) && syn.priorities.length) {
      lines.push('### ✅ 行动清单（按优先级）')
      syn.priorities.forEach((p, i) => {
        const act = typeof p === 'string' ? p : p.action || ''
        const why = typeof p === 'object' && p && p.why ? ` —— ${p.why}` : ''
        lines.push(`${i + 1}. ${act}${why}`)
      })
      lines.push('')
    }
  }
  lines.push('## 各模型分析')
  lines.push('')
  for (const r of report.results || []) {
    const m = MODEL_BY_ID[r.id]
    lines.push(`### ${m ? m.name : r.id}${m && m.en ? `（${m.en}）` : ''}`)
    if (r.verdict) lines.push(`**结论**：${r.verdict}`)
    lines.push('')
    if (r.analysis) { lines.push(r.analysis); lines.push('') }
    if (Array.isArray(r.insights) && r.insights.length) {
      for (const s of r.insights) lines.push(`- ${s}`)
      lines.push('')
    }
    if (Array.isArray(r.actions) && r.actions.length) {
      lines.push('建议行动：')
      for (const s of r.actions) lines.push(`1. ${s}`)
      lines.push('')
    }
  }
  return lines.join('\n')
}

